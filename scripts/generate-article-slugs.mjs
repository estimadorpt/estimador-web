#!/usr/bin/env node
// Emit the list of published article slugs for the analytics path reducer.
//
// The reducer runs in the browser, so it cannot enumerate src/content/articles
// itself, and it must not trust the slug in the URL bar. This writes the set of
// slugs that actually exist into a plain module the client bundle can import,
// which keeps analyticsPath a pure function of its argument.
//
//   node scripts/generate-article-slugs.mjs           # write the module
//   node scripts/generate-article-slugs.mjs --check   # fail if it is stale
//
// Run it after publishing a piece. Forgetting only costs that piece its own
// row in the analytics — it collapses into the /artigos/artigo/ bucket, and
// nothing about the reader leaks either way — but the test suite fails on the
// drift so the omission does not go unnoticed.

import fs from 'node:fs';
import path from 'node:path';

const CONTENT_DIR = path.join(process.cwd(), 'src/content/articles');
const OUTPUT_FILE = path.join(process.cwd(), 'src/lib/published-articles.generated.ts');
const LOCALES = ['pt', 'en'];

// Mirrors the pattern the article loader enforces on a filename.
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

// Same shape the loader parses. Read here rather than imported because this is
// a plain script and the loader is TypeScript.
const METADATA_PATTERN = /^export const metadata = (\{[\s\S]*?\n\});?\s*/;

/** A draft is excluded from a production export, so no page of it can be read. */
function isDraft(file) {
  const match = fs.readFileSync(file, 'utf8').match(METADATA_PATTERN);
  if (!match) return false;
  try {
    return JSON.parse(match[1]).draft === true;
  } catch {
    // A malformed header is the article loader's error to raise, not this
    // script's — it fails the build with a better message than we could.
    return false;
  }
}

// The category an unrecognised path under /artigos collapses to. An article
// slugged this way would silently share a row with that bucket, so the two
// numbers would stop meaning anything.
const RESERVED_SLUG = 'artigo';

function collectSlugs() {
  const slugs = new Set();
  for (const locale of LOCALES) {
    const dir = path.join(CONTENT_DIR, locale);
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir)) {
      if (!file.endsWith('.mdx')) continue;
      const slug = file.slice(0, -4);
      if (!SLUG_PATTERN.test(slug)) {
        console.error(`Article filename is not a valid slug: ${locale}/${file}`);
        process.exit(1);
      }
      if (slug === RESERVED_SLUG) {
        console.error(`"${RESERVED_SLUG}" is reserved as the unrecognised-path category; rename ${locale}/${file}`);
        process.exit(1);
      }
      // Reserved for test scaffolding, the same way "artigo" is reserved below.
      // A fixture exists for the length of one test file and must never appear
      // in a list the browser bundle ships.
      if (slug.startsWith('fixture-')) continue;
      if (isDraft(path.join(dir, file))) continue;
      slugs.add(slug);
    }
  }
  // A piece published in one language only is still a published page: /en/ of a
  // Portuguese-only slug falls back to the Portuguese text and is really read.
  //
  // Drafts are not. They are excluded from the production export, so no reader
  // can ever land on one, and a slug nobody can reach earns no row. Keeping
  // them out also stops this list disagreeing with the content directory while
  // a test fixture is on disk — the drift check reads that directory directly.
  return [...slugs].sort();
}

function render(slugs) {
  return `// Generated by scripts/generate-article-slugs.mjs — do not edit by hand.
//
// Slugs of every published article, in either language. analyticsPath() checks
// a path under /artigos against this list instead of trusting the URL.
export const PUBLISHED_ARTICLE_SLUGS: readonly string[] = [
${slugs.map(slug => `  '${slug}',`).join('\n')}
];
`;
}

const slugs = collectSlugs();
const contents = render(slugs);

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : '';
  if (current !== contents) {
    console.error('src/lib/published-articles.generated.ts is stale. Run: node scripts/generate-article-slugs.mjs');
    process.exit(1);
  }
  console.log(`Article slug list is current (${slugs.length} slugs).`);
} else {
  fs.writeFileSync(OUTPUT_FILE, contents);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)} (${slugs.length} slugs).`);
}
