import { setRequestLocale } from '@/i18n/request-locale';
import { Users } from 'lucide-react';
import { Header } from '@/components/Header';
import { SiteFooter } from '@/components/SiteFooter';
import { PageHero } from '@/components/PageHero';
import { Mosaic } from '@/components/brand/Mosaic';
import { SectionNotes } from '@/components/articles/SectionNotes';
import { ParishSearch } from '@/components/population/ParishSearch';
import { PopulationSectionNav } from '@/components/population/SectionNav';
import { PopulationMap } from '@/components/population/map/PopulationMap';
import { KeyFacts } from '@/components/population/hub/KeyFacts';
import { NationalAgeCard } from '@/components/population/hub/NationalAgeCard';
import { EntryCards } from '@/components/population/hub/EntryCards';
import { RegionsIndex } from '@/components/population/hub/RegionsIndex';
import { regionEntries } from '@/components/population/hub/places';
import { POPULATION_RELEASE } from '@/lib/config/population';
import { createPageMetadata } from '@/lib/metadata';
import { readCells } from '@/lib/population/compact';
import { HONESTY, type Locale } from '@/lib/population/labels';
import { loadPopulationMeta, loadPopulationNational, loadPopulationPlaces } from '@/lib/utils/population-data-loader';
import type { Metadata } from 'next';

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  setRequestLocale(locale);
  const pt = locale !== 'en';
  return createPageMetadata({
    locale,
    path: '/populacao',
    title: pt
      ? `Quem vive em Portugal, freguesia a freguesia? População sintética v${POPULATION_RELEASE}`
      : `Who lives in Portugal, parish by parish? Synthetic population v${POPULATION_RELEASE}`,
    description: pt
      ? 'Uma população sintética de acesso aberto para as 3 092 freguesias de Portugal, gerada a partir dos Censos 2021: procura a tua freguesia, explora o mapa e descarrega os dados.'
      : 'An open-access synthetic population for all 3,092 parishes in Portugal, generated from the 2021 Census: find your parish, explore the map and download the data.',
    index: true,
  });
}

export default async function PopulationHub({ params }: { params: Promise<{ locale: string }> }) {
  const { locale: raw } = await params;
  const locale: Locale = raw === 'en' ? 'en' : 'pt';
  setRequestLocale(locale);
  const pt = locale === 'pt';
  const [meta, places, national] = await Promise.all([loadPopulationMeta(), loadPopulationPlaces(), loadPopulationNational()]);
  const regions = places ? regionEntries(places, locale) : [];
  const ageCells = meta && national && national.response.decision !== 'refuse'
    ? readCells(national.response, meta.recipes.national_age, locale)
    : null;

  return (
    <div className="min-h-screen bg-paper">
      <Header />
      <main id="main-content" tabIndex={-1}>
      <PageHero
        field="periwinkle"
        // The search's suggestion list opens below the hero; the art stays inside its own box.
        className="overflow-visible!"
        icon={<Users aria-hidden="true" className="h-4 w-4" />}
        eyebrow={pt ? `População sintética · v${POPULATION_RELEASE} · Censos 2021` : `Synthetic population · v${POPULATION_RELEASE} · 2021 Census`}
        title={pt ? 'Quem vive em Portugal, freguesia a freguesia?' : 'Who lives in Portugal, parish by parish?'}
        lede={
          <>
            {HONESTY.positioning[locale]}{' '}
            {pt
              ? 'São pessoas e agregados gerados por um modelo e calibrados nas tabelas dos Censos de cada lugar. Escolhe uma freguesia para ver o que a população gerada diz sobre ela.'
              : 'They are people and households generated by a model and calibrated to each place’s Census tables. Pick a parish to see what the generated population says about it.'}
          </>
        }
        art={<Mosaic variant="cover" className="h-full w-full" ground="transparent" colors={['mintSoft', 'mustardSoft', 'coralSoft']} />}
        actions={
          <ParishSearch
            locale={locale}
            withLocation
            label={pt ? 'Procura a tua freguesia' : 'Find your parish'}
            className="w-full max-w-xl"
          />
        }
      />
      <PopulationSectionNav current="hub" locale={locale} />

      <div className="mx-auto max-w-7xl px-4 py-8 md:py-10">
        {meta ? (
          <KeyFacts
            locale={locale}
            persons={meta.counts.persons}
            households={meta.counts.households}
            parishes={meta.counts.parishes}
            municipalities={meta.counts.municipalities}
            tiers={meta.counts.tiers}
          />
        ) : (
          <p className="rounded-2xl border border-line bg-cream p-5 text-sm text-stone-600">
            {pt
              ? 'Os dados da população sintética não estão disponíveis neste momento. Tenta novamente mais tarde.'
              : 'The synthetic population data is not available right now. Please try again later.'}
          </p>
        )}

        <section aria-labelledby="mapa" className="mt-12">
          <h2 id="mapa" className="text-2xl md:text-3xl">{pt ? 'Explora o mapa' : 'Explore the map'}</h2>
          <p className="mb-4 mt-2 max-w-3xl text-[15px] leading-relaxed text-stone-600">
            {pt
              ? 'Aproxima um distrito, depois um concelho, e escolhe uma freguesia. A cor de cada freguesia diz só o nível de qualidade do ajuste às tabelas do INE (A, B ou C); não mede nada sobre quem lá vive.'
              : 'Zoom into a district, then a municipality, and pick a parish. A parish’s colour says only its quality-of-fit tier against INE’s tables (A, B or C); it measures nothing about who lives there.'}
          </p>
          <PopulationMap locale={locale} />
        </section>

        {ageCells && (
          <section id="idade" aria-labelledby="idade-titulo" className="mt-12 scroll-mt-24">
            <h2 id="idade-titulo" className="mb-4 text-2xl md:text-3xl">{pt ? 'Que idade tem Portugal?' : 'How old is Portugal?'}</h2>
            <NationalAgeCard cells={ageCells} locale={locale} />
          </section>
        )}

        <section aria-labelledby="mais" className="mt-12">
          <h2 id="mais" className="mb-4 text-2xl md:text-3xl">{pt ? 'E agora?' : 'What next?'}</h2>
          <EntryCards locale={locale} />
        </section>

        {regions.length > 0 && (
          <section aria-labelledby="regioes" className="mt-12">
            <h2 id="regioes" className="text-2xl md:text-3xl">{pt ? 'Freguesias por distrito e região autónoma' : 'Parishes by district and autonomous region'}</h2>
            <p className="mb-4 mt-2 max-w-3xl text-[15px] leading-relaxed text-stone-600">
              {pt
                ? 'Cada página lista os concelhos e as freguesias, por ordem alfabética, com a ligação para cada uma.'
                : 'Each page lists the municipalities and parishes in alphabetical order, with a link to each one.'}
            </p>
            <RegionsIndex regions={regions} locale={locale} />
          </section>
        )}
      </div>

      <SectionNotes
        section="demographics"
        locale={locale}
        className="border-t border-line py-10"
        containerClassName="mx-auto max-w-7xl px-4"
      />
      </main>
      <SiteFooter locale={locale} />
    </div>
  );
}
