import { setRequestLocale } from '@/i18n/request-locale';
import { Header } from '@/components/Header';
import { SiteFooter } from '@/components/SiteFooter';
import { PageHero } from '@/components/PageHero';
import { SectionNotes } from '@/components/articles/SectionNotes';
import { ParishSearch } from '@/components/population/ParishSearch';
import { PopulationSectionNav } from '@/components/population/SectionNav';
import { PopulationMap } from '@/components/population/map/PopulationMap';
import { KeyFacts } from '@/components/population/hub/KeyFacts';
import { NationalAgeCard } from '@/components/population/hub/NationalAgeCard';
import { EntryCards } from '@/components/population/hub/EntryCards';
import { RegionsIndex } from '@/components/population/hub/RegionsIndex';
import { regionEntries } from '@/components/population/hub/places';
import { POPULATION_RELEASE, POPULATION_ROUTES } from '@/lib/config/population';
import { TextLink } from '@/components/brand/TextLink';
import { ArrowRight } from 'lucide-react';
import { createPageMetadata } from '@/lib/metadata';
import { readCells } from '@/lib/population/compact';
import { formatCount } from '@/lib/population/format';
import { HONESTY, type Locale } from '@/lib/population/labels';
import { loadPopulationMeta, loadPopulationNational, loadPopulationPlaces } from '@/lib/utils/population-data-loader';
import type { Metadata } from 'next';

export async function generateMetadata({ params }: { params: Promise<{ locale: string }> }): Promise<Metadata> {
  const { locale } = await params;
  setRequestLocale(locale);
  const pt = locale !== 'en';
  // The count is the release's own (meta.json), as on the page and the homepage panel.
  const meta = await loadPopulationMeta();
  const parishes = meta ? formatCount(meta.counts.parishes, pt ? 'pt' : 'en') : (pt ? '3 092' : '3,092');
  return createPageMetadata({
    locale,
    path: '/populacao',
    title: pt
      ? `As ${parishes} freguesias dos Censos 2021, uma a uma`
      : `The ${parishes} parishes of the 2021 Census, one by one`,
    description: pt
      ? `Uma população sintética aberta para as ${parishes} freguesias dos Censos 2021: procura a tua freguesia, explora o mapa e faz download dos dados.`
      : `An open synthetic population for the ${parishes} parishes of the 2021 Census: find your parish, explore the map and download the data.`,
    index: true,
  });
}

export default async function PopulationHub({ params }: { params: Promise<{ locale: string }> }) {
  const { locale: raw } = await params;
  const locale: Locale = raw === 'en' ? 'en' : 'pt';
  setRequestLocale(locale);
  const pt = locale === 'pt';
  const [meta, places, national] = await Promise.all([loadPopulationMeta(), loadPopulationPlaces(), loadPopulationNational()]);
  const regions = places ? regionEntries(places, locale) : [];
  const ageCells = meta && national && national.response.decision !== 'refuse'
    ? readCells(national.response, meta.recipes.national_age, locale)
    : null;
  // The statement the homepage panel makes, with the release's own count.
  const parishes = meta ? formatCount(meta.counts.parishes, locale) : (pt ? '3 092' : '3,092');

  return (
    <div className="min-h-screen bg-paper">
      <Header />
      <main id="main-content" tabIndex={-1}>
      <PopulationSectionNav current="hub" locale={locale} />
      <PageHero
        compact
        measure="wide"
        // The search's suggestion list opens below the hero: the hero must not clip it.
        className="overflow-visible!"
        eyebrow={pt ? `População sintética · v${POPULATION_RELEASE} · Censos 2021` : `Synthetic population · v${POPULATION_RELEASE} · 2021 Census`}
        title={pt ? `As ${parishes} freguesias dos Censos 2021, uma a uma` : `The ${parishes} parishes of the 2021 Census, one by one`}
        lede={
          <>
            {pt
              ? 'Pessoas e agregados gerados por um modelo, freguesia a freguesia, a partir das tabelas dos Censos 2021 de cada lugar: idades, trabalho, escolaridade e famílias. Escolhe uma freguesia para ver o que a população gerada diz sobre ela.'
              : 'People and households generated by a model, parish by parish, from each place’s 2021 Census tables: ages, work, education and families. Pick a parish to see what the generated population says about it.'}
            <span className="mt-2 block text-[15px] text-graphite">{HONESTY.positioning[locale]}</span>
            {/* The explainer, up here beside the release's own words rather than at the
                foot of the page: it is how a first-time reader learns to read the rest. */}
            <span className="mt-2 block text-[15px] text-graphite">
              <TextLink href={POPULATION_ROUTES.explainer} locale={locale}>
                {pt ? 'Como ler uma população sintética' : 'How to read a synthetic population'}
                <ArrowRight aria-hidden="true" className="ml-1 h-4 w-4" />
              </TextLink>
              <span className="block">
                {pt
                  ? 'Um bairro imaginado, com 100 pessoas inventadas, mostra como ler e como se constrói uma população sintética.'
                  : 'An imagined neighbourhood of 100 invented people shows how a synthetic population is read and how it is built.'}
              </span>
            </span>
          </>
        }
        actions={
          <ParishSearch
            locale={locale}
            withLocation
            label={pt ? 'Procura a tua freguesia' : 'Find your parish'}
            className="w-full max-w-xl"
          />
        }
      />

      <div className="mx-auto max-w-7xl px-4 py-8 md:py-10">
        {meta ? (
          <KeyFacts
            locale={locale}
            persons={meta.counts.persons}
            households={meta.counts.households}
            parishes={meta.counts.parishes}
            municipalities={meta.counts.municipalities}
            tiers={meta.counts.tiers}
          />
        ) : (
          <p className="border-t border-rule pt-3 text-sm text-graphite">
            {pt
              ? 'Os dados da população sintética não estão disponíveis neste momento. Tenta novamente mais tarde.'
              : 'The synthetic population data is not available right now. Please try again later.'}
          </p>
        )}

        <section aria-labelledby="mapa" className="mt-12">
          <h2 id="mapa" className="border-b border-ink pb-2 text-[26px] leading-7 md:text-[28px] md:leading-8">{pt ? 'O mapa das freguesias' : 'The parish map'}</h2>
          <p className="mb-4 mt-3 max-w-3xl text-[15px] leading-relaxed text-graphite">
            {pt
              ? 'Aproxima um distrito, depois um concelho, e escolhe uma freguesia. O preenchimento de cada freguesia é só o seu nível de qualidade (A em branco, B tracejado, C quadriculado), que junta o ajuste às tabelas do INE e o número de residentes; não é um número da população gerada.'
              : 'Zoom into a district, then a municipality, and pick a parish. A parish’s fill is only its quality tier (A plain, B hatched, C cross-hatched), which combines the fit to INE’s tables and the number of residents; it is not a figure from the generated population.'}
          </p>
          <PopulationMap locale={locale} />
        </section>

        {ageCells && (
          <section id="idade" aria-labelledby="idade-titulo" className="mt-12">
            <h2 id="idade-titulo" tabIndex={-1} className="mb-4 text-[26px] leading-7 md:text-[28px] md:leading-8">{pt ? 'Idades em Portugal' : 'Ages in Portugal'}</h2>
            <NationalAgeCard cells={ageCells} locale={locale} id={national?.response.id ?? null} headingId="idade-titulo" />
          </section>
        )}

        <section aria-labelledby="mais" className="mt-12">
          <h2 id="mais" className="mb-4 text-[26px] leading-7 md:text-[28px] md:leading-8">{pt ? 'Para continuar' : 'To go further'}</h2>
          <EntryCards locale={locale} />
        </section>

        {regions.length > 0 && (
          <section aria-labelledby="regioes" className="mt-12">
            <h2 id="regioes" className="text-[26px] leading-7 md:text-[28px] md:leading-8">{pt ? 'Freguesias por distrito e região autónoma' : 'Parishes by district and autonomous region'}</h2>
            <p className="mb-4 mt-2 max-w-3xl text-[15px] leading-relaxed text-graphite">
              {pt
                ? 'Cada página lista os concelhos e as freguesias, por ordem alfabética, com o link para cada uma.'
                : 'Each page lists the municipalities and parishes in alphabetical order, with a link to each one.'}
            </p>
            <RegionsIndex regions={regions} locale={locale} />
          </section>
        )}
      </div>

      <SectionNotes
        section="demographics"
        locale={locale}
        className="border-t border-rule py-10"
        containerClassName="mx-auto max-w-7xl px-4"
      />
      </main>
      <SiteFooter locale={locale} />
    </div>
  );
}
